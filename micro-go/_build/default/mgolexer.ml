  (* fonction qui met insert_semi à true si le dernier token est dans l'ensemble donné par le sujet *)
  let mark token =
    insert_semi :=
      (match token with
       | IDENT _ | INT _ | STRING _
       | TRUE | FALSE | NIL
       | RETURN | INCR | DECR
       | RPAR | END -> true
       | _ -> false);
    token

  let unmark token =
    insert_semi := false;
    token
